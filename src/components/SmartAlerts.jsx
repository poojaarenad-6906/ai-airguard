import { useState, useEffect } from 'react';
import { getAqiLevel } from '../utils/aqiHelpers';

export default function SmartAlerts({ data, hotspots = [] }) {
  const [alerts, setAlerts] = useState([]);
  const [dismissed, setDismissed] = useState(new Set());

  useEffect(() => {
    const generated = generateAlerts(data, hotspots);
    setAlerts(generated);
  }, [data, hotspots]);

  function generateAlerts(d, spots) {
    const list = [];
    const aqi = Number(d?.aqi) || 0;

    if (aqi > 300) list.push({ id: 'aqi-severe', type: 'critical', icon: '🚨', title: 'SEVERE Air Quality Alert', message: `AQI ${aqi} at ${d.location || d.city} — HAZARDOUS conditions. All outdoor activities strongly discouraged.`, time: 'Now', action: 'Stay indoors, seal windows, run air purifier' });
    else if (aqi > 200) list.push({ id: 'aqi-poor', type: 'warning', icon: '⚠️', title: 'Poor Air Quality Warning', message: `AQI ${aqi} at ${d.location || d.city} is in POOR category. Health effects possible for everyone.`, time: 'Now', action: 'Limit outdoor activity, wear N95 mask' });
    else if (aqi > 150) list.push({ id: 'aqi-moderate', type: 'info', icon: '🟡', title: 'Elevated Pollution Notice', message: `AQI ${aqi} — Moderate-High range. Sensitive groups should take precautions.`, time: 'Now', action: 'Masks recommended for outdoor activities' });

    if (d?.pm25 > 60) list.push({ id: 'pm25-high', type: 'warning', icon: '💨', title: 'PM2.5 Exceeds CPCB Standard', message: `PM2.5 at ${d.pm25} μg/m³ exceeds the 24-hour standard of 60 μg/m³. Fine particles penetrate deep into lungs.`, time: 'Now', action: 'Use N95/N99 mask, avoid road-side exposure' });
    if (d?.pm10 > 100) list.push({ id: 'pm10-high', type: 'info', icon: '🌫️', title: 'Elevated PM10 (Coarse Dust)', message: `PM10 at ${d.pm10} μg/m³ — elevated dust levels. Road dust and construction contributing.`, time: 'Now', action: 'Irrigate streets, reduce construction dust' });
    if (d?.no2 > 80) list.push({ id: 'no2-high', type: 'warning', icon: '⚗️', title: 'High NO₂ Levels', message: `Nitrogen dioxide at ${d.no2} μg/m³ — indicates heavy vehicular and industrial emissions.`, time: 'Now', action: 'Avoid roadside activities, peak traffic hours' });

    const hour = new Date().getHours();
    if (hour >= 7 && hour <= 10) list.push({ id: 'rush-morning', type: 'info', icon: '🚦', title: 'Morning Rush Hour Alert', message: 'Peak traffic period (7–10 AM) — AQI typically 25–40% higher than baseline. Bengaluru traffic at maximum.', time: 'Active now', action: 'Delay outdoor activity by 2–3 hours if possible' });
    if (hour >= 17 && hour <= 20) list.push({ id: 'rush-evening', type: 'info', icon: '🚦', title: 'Evening Rush Hour Alert', message: 'Peak traffic period (5–8 PM) — worst pollution window of the day in Bengaluru.', time: 'Active now', action: 'Stay indoors or use AC vehicle' });

    // Hotspot alerts
    const criticalSpots = spots.filter(h => (h.aqi || 0) > 200).slice(0, 2);
    criticalSpots.forEach(h => {
      list.push({ id: `hotspot-${h.name}`, type: 'warning', icon: '🔥', title: `Pollution Hotspot: ${h.name}`, message: `${h.name} reporting AQI ${h.aqi} — significantly above city average. Avoid this area if possible.`, time: 'Now', action: 'Find alternative routes, limit exposure time' });
    });

    // Seasonal/construction
    list.push({ id: 'construction', type: 'info', icon: '🏗️', title: 'Active Construction Zones', message: 'Metro Phase 2 and Peripheral Ring Road construction causing elevated PM10 in multiple areas. Dust warnings active.', time: 'Ongoing', action: 'Water spraying required at construction sites' });

    return list;
  }

  const dismiss = (id) => setDismissed(prev => new Set([...prev, id]));
  const visible = alerts.filter(a => !dismissed.has(a.id));

  const alertColors = {
    critical: { bg: 'rgba(147,51,234,0.1)', border: 'rgba(147,51,234,0.4)', label: '#9333EA' },
    warning:  { bg: 'rgba(239,68,68,0.08)', border: 'rgba(239,68,68,0.35)', label: '#EF4444' },
    info:     { bg: 'rgba(234,179,8,0.08)', border: 'rgba(234,179,8,0.3)',  label: '#EAB308' },
    success:  { bg: 'rgba(34,197,94,0.08)', border: 'rgba(34,197,94,0.3)',  label: '#22C55E' },
  };

  return (
    <div style={{ maxWidth: 1280, margin: '0 auto', padding: '0 24px 40px' }}>
      <div style={{ marginBottom: 24 }}>
        <h2 className="section-title">🚨 Smart Alerts</h2>
        <p className="section-subtitle">{visible.length} active alerts for {data?.location || data?.city || 'your area'} · Auto-generated by AI monitoring agents</p>
      </div>

      {visible.length === 0 && (
        <div className="glass-card" style={{ padding: 48, textAlign: 'center' }}>
          <div style={{ fontSize: '3rem', marginBottom: 16 }}>✅</div>
          <h3 style={{ color: '#22C55E' }}>All Clear</h3>
          <p style={{ color: '#8BA8C4' }}>No critical alerts. {dismissed.size > 0 && `(${dismissed.size} dismissed)`}</p>
        </div>
      )}

      <div style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
        {visible.map(alert => {
          const style = alertColors[alert.type] || alertColors.info;
          return (
            <div key={alert.id} className="glass-card fade-in" style={{ background: style.bg, borderColor: style.border, padding: '16px 20px' }}>
              <div style={{ display: 'flex', gap: 14, alignItems: 'flex-start' }}>
                <span style={{ fontSize: '1.6rem', flexShrink: 0 }}>{alert.icon}</span>
                <div style={{ flex: 1 }}>
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 6, flexWrap: 'wrap', gap: 8 }}>
                    <h3 style={{ color: style.label, fontSize: '0.95rem', fontWeight: 700 }}>{alert.title}</h3>
                    <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
                      <span style={{ color: '#8BA8C4', fontSize: '0.75rem' }}>⏰ {alert.time}</span>
                      <span className="badge" style={{ background: style.bg, color: style.label, border: `1px solid ${style.border}`, fontSize: '0.68rem', textTransform: 'capitalize' }}>{alert.type}</span>
                    </div>
                  </div>
                  <p style={{ color: '#DBEAFE', fontSize: '0.86rem', marginBottom: 8, lineHeight: 1.6 }}>{alert.message}</p>
                  <div style={{ padding: '7px 12px', background: 'rgba(56,189,248,0.07)', borderRadius: 6, display: 'inline-block' }}>
                    <span style={{ color: '#38BDF8', fontSize: '0.78rem' }}>💡 Action: </span>
                    <span style={{ color: '#DBEAFE', fontSize: '0.78rem' }}>{alert.action}</span>
                  </div>
                </div>
                <button className="btn btn-ghost btn-sm" onClick={() => dismiss(alert.id)} style={{ flexShrink: 0, padding: '4px 8px', fontSize: '0.75rem' }}>✕</button>
              </div>
            </div>
          );
        })}
      </div>

      {dismissed.size > 0 && (
        <button className="btn btn-ghost btn-sm" style={{ marginTop: 20 }} onClick={() => setDismissed(new Set())}>
          🔄 Show {dismissed.size} dismissed alert(s)
        </button>
      )}
    </div>
  );
}
